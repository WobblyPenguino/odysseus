from __future__ import annotations

import re
from typing import Any


def deterministic_simple_project(goal: str, analysis: dict[str, Any]) -> dict[str, Any] | None:
    """Narrow one-file fallback when the local LLM is unavailable."""
    low = (goal or "").lower()
    wants_one_file = any(x in low for x in ["one file", "single file", "just one file", "only one file"])
    wants_script = (analysis.get("artifact_type") == "automation_script") or "script" in low
    if not (wants_script or wants_one_file):
        return None
    if any(x in low for x in ["game", "website", "web app", "html", "browser"]):
        return None
    script = _script_for_goal(goal)
    return {
        "folder": _slug(goal) or "nova_script",
        "main_file": "script.py",
        "run_command": "python script.py \"let there be let\"",
        "verify_command": "python -m py_compile script.py",
        "notes": "Deterministic one-file fallback used because the local model did not return output.",
        "source": "deterministic_fallback",
        "creation_analysis": analysis,
        "files": {"script.py": script},
        "assumptions": ["User asked for a simple script; generated exactly one Python file instead of a generic scaffold."],
    }


def _script_for_goal(goal: str) -> str:
    low = (goal or "").lower()
    word = "let"
    m = re.search(r"bolds?\s+([a-zA-Z0-9_-]+)", low)
    if m:
        word = m.group(1)
    return f'''#!/usr/bin/env python3
"""Simple text helper generated by Nova.

It bolds the target word in input text using Markdown **bold** markers.
Usage:
    python script.py "let there be let"
    echo "let there be light" | python script.py
"""
from __future__ import annotations

import re
import sys

TARGET = {word!r}


def bold_word(text: str, target: str = TARGET) -> str:
    pattern = re.compile(r"\\b(" + re.escape(target) + r")\\b", re.IGNORECASE)
    return pattern.sub(lambda m: "**" + m.group(1) + "**", text)


def main(argv: list[str]) -> int:
    text = " ".join(argv[1:]) if len(argv) > 1 else sys.stdin.read()
    if not text:
        print("Usage: python script.py \\\"text containing {word}\\\"")
        return 2
    print(bold_word(text))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
'''


def _slug(text: str) -> str:
    s = re.sub(r"[^a-zA-Z0-9]+", "_", text.lower()).strip("_")
    return s[:48] or "nova_script"
