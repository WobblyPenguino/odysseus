from __future__ import annotations

import difflib
import json
import shutil
import subprocess
import sys
import time
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any

from .safe_io import atomic_write_text, atomic_write_json

SAFE_SUFFIXES = {".py", ".md", ".json", ".txt", ".html", ".css", ".js", ".bat", ".ps1", ".yml", ".yaml"}
BLOCKED_PARTS = {".git", "__pycache__", ".venv", "venv", "node_modules", "data", "logs", "uploads", "generated", "dist", "build"}


@dataclass(frozen=True)
class NovaFileChange:
    path: str
    content: str
    reason: str


@dataclass(frozen=True)
class NovaVerifiedChangeSet:
    id: str
    title: str
    source: str
    risk: str
    description: str
    odysseus_feature_source: str
    validation_commands: tuple[str, ...]
    changes: tuple[NovaFileChange, ...] = field(default_factory=tuple)


def _now_stamp() -> str:
    return time.strftime("%Y%m%d_%H%M%S")


def _is_safe_relative_path(path: str) -> tuple[bool, str]:
    if not path or Path(path).is_absolute():
        return False, "path must be a non-empty relative path"
    p = Path(path)
    if any(part in BLOCKED_PARTS for part in p.parts):
        return False, "path targets a blocked runtime/build/private directory"
    if ".." in p.parts:
        return False, "path traversal is not allowed"
    if p.suffix and p.suffix.lower() not in SAFE_SUFFIXES:
        return False, f"file suffix {p.suffix!r} is not in the safe allow-list"
    return True, "ok"


def _read(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except Exception:
        return ""


def _diff(path: str, old: str, new: str) -> str:
    return "".join(
        difflib.unified_diff(
            old.splitlines(True),
            new.splitlines(True),
            fromfile=f"a/{path}",
            tofile=f"b/{path}",
            lineterm="",
        )
    )


def _default_validation_commands() -> tuple[str, ...]:
    return (
        f"{sys.executable} -m compileall -q app.py winlocalassistant",
        f"{sys.executable} app.py /version",
        f"{sys.executable} app.py /nova-eval-packs run core",
    )


