def _select_changeset(change_id: str | None) -> NovaVerifiedChangeSet | None:
    changes = builtin_changesets()
    if not change_id:
        return next(iter(changes.values()))
    key = change_id.strip().lower()
    return changes.get(key)


def build_verified_change_plan(root: Path, change_id: str | None = None) -> dict[str, Any]:
    root = Path(root).resolve()
    sets = builtin_changesets()
    selected = _select_changeset(change_id)
    payload: dict[str, Any] = {
        "ok": bool(selected) or not change_id,
        "mode": "plan",
        "root": str(root),
        "available_changesets": [asdict(item) for item in sets.values()],
        "selected_id": selected.id if selected else None,
        "validation_policy": "preview -> confirm -> backup -> write -> validate -> rollback on failure -> receipt",
        "usage": "/nova-self-apply preview CHANGE_ID or /nova-self-apply apply CHANGE_ID --confirm",
    }
    if change_id and not selected:
        payload["ok"] = False
        payload["error"] = f"Unknown change set: {change_id}"
    return payload


def preview_verified_change(root: Path, change_id: str | None = None) -> dict[str, Any]:
    root = Path(root).resolve()
    selected = _select_changeset(change_id)
    if not selected:
        return {"ok": False, "mode": "preview", "error": f"Unknown change set: {change_id}", "root": str(root)}
    diffs = []
    safety = []
    for change in selected.changes:
        ok, reason = _is_safe_relative_path(change.path)
        target = root / change.path
        old = _read(target)
        diffs.append({"path": change.path, "reason": change.reason, "safe": ok, "safety_reason": reason, "diff": _diff(change.path, old, change.content)})
        safety.append(ok)
    return {"ok": all(safety), "mode": "preview", "root": str(root), "changeset": asdict(selected), "diffs": diffs}


def _run_validation(root: Path, commands: tuple[str, ...]) -> list[dict[str, Any]]:
    results = []
    for command in commands:
        started = time.time()
        proc = subprocess.run(command, cwd=str(root), shell=True, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, timeout=60)
        output = (proc.stdout or "")[-4000:]
        results.append({"command": command, "returncode": proc.returncode, "ok": proc.returncode == 0, "seconds": round(time.time() - started, 3), "output": output})
    return results


def apply_verified_change(root: Path, change_id: str | None = None, *, confirm: bool = False) -> dict[str, Any]:
    root = Path(root).resolve()
    selected = _select_changeset(change_id)
    if not selected:
        return {"ok": False, "mode": "apply", "error": f"Unknown change set: {change_id}", "root": str(root)}
    preview = preview_verified_change(root, selected.id)
    if not preview.get("ok"):
        return {"ok": False, "mode": "apply", "status": "blocked", "root": str(root), "preview": preview}
    if not confirm:
        return {"ok": False, "mode": "apply", "status": "confirmation_required", "root": str(root), "changeset": asdict(selected), "next_step": f"/nova-self-apply apply {selected.id} --confirm", "preview": preview}

    stamp = _now_stamp()
    backup_dir = root / ".nova_backups" / "verified_changes" / f"{stamp}_{selected.id}"
    backup_dir.mkdir(parents=True, exist_ok=True)
    applied: list[dict[str, Any]] = []
    receipt_path = root / "docs" / "NOVA_VERIFIED_CHANGE_RECEIPT_LATEST.json"
    try:
        for change in selected.changes:
            ok, reason = _is_safe_relative_path(change.path)
            if not ok:
                raise RuntimeError(f"Unsafe path {change.path}: {reason}")
            target = root / change.path
            target.parent.mkdir(parents=True, exist_ok=True)
            existed = target.exists()
            old = _read(target) if existed else ""
            backup_file = backup_dir / (change.path.replace("/", "__") + ".bak")
            atomic_write_text(backup_file, old)
            atomic_write_text(target, change.content)
            applied.append({"path": change.path, "existed": existed, "backup": str(backup_file), "reason": change.reason})
        validation = _run_validation(root, selected.validation_commands)
        validation_ok = all(item.get("ok") for item in validation)
        status = "applied"
        rolled_back = False
        if not validation_ok:
            for item in reversed(applied):
                target = root / item["path"]
                backup_text = _read(Path(item["backup"]))
                if item.get("existed"):
                    atomic_write_text(target, backup_text)
                else:
                    try:
                        target.unlink()
                    except FileNotFoundError:
                        pass
            status = "rolled_back_after_validation_failure"
            rolled_back = True
        receipt = {
            "ok": validation_ok,
            "mode": "apply",
            "status": status,
            "changeset": asdict(selected),
            "root": str(root),
            "applied": applied,
            "validation": validation,
            "rolled_back": rolled_back,
            "backup_dir": str(backup_dir),
            "generated_at": time.strftime("%Y-%m-%d %H:%M:%S"),
        }
        receipt_path.parent.mkdir(parents=True, exist_ok=True)
        atomic_write_json(receipt_path, receipt, ensure_ascii=True)
        receipt["receipt_path"] = str(receipt_path)
        return receipt
    except Exception as exc:
        for item in reversed(applied):
            target = root / item["path"]
            backup_text = _read(Path(item["backup"]))
            if item.get("existed"):
                atomic_write_text(target, backup_text)
            else:
                try:
                    target.unlink()
                except FileNotFoundError:
                    pass
        return {"ok": False, "mode": "apply", "status": "error_rolled_back", "error": repr(exc), "root": str(root), "applied_before_error": applied}


def render_verified_change(payload: dict[str, Any]) -> str:
    mode = payload.get("mode", "plan")
    lines = ["# Nova Verified Self-Apply", "", f"Mode: **{mode}**", f"Status: **{payload.get('status', 'ready' if payload.get('ok', True) else 'attention')}**"]
    if payload.get("error"):
        lines += ["", f"Error: {payload.get('error')}"]
    if mode == "plan":
        lines += ["", "## Available change sets"]
        for item in payload.get("available_changesets", []):
            lines.append(f"- `{item.get('id')}` — {item.get('title')} (risk={item.get('risk')})")
        lines += ["", "Usage: `" + payload.get("usage", "/nova-self-apply preview CHANGE_ID") + "`"]
    elif mode == "preview":
        cs = payload.get("changeset") or {}
        lines += ["", f"Change set: `{cs.get('id', '')}` — {cs.get('title', '')}", "", "## Diffs"]
        for item in payload.get("diffs", []):
            lines.append(f"### `{item.get('path')}`")
            lines.append(f"Safety: {'PASS' if item.get('safe') else 'BLOCKED'} — {item.get('safety_reason')}")
            diff = item.get("diff") or "(no textual diff)"
            lines.append("```diff")
            lines.append(diff[:6000])
            lines.append("```")
        if payload.get("ok"):
            lines += ["", "Apply with ` /nova-self-apply apply CHANGE_ID --confirm` after review."]
    elif mode == "apply":
        cs = payload.get("changeset") or {}
        lines += ["", f"Change set: `{cs.get('id', '')}`", f"Rolled back: **{payload.get('rolled_back', False)}**"]
        if payload.get("next_step"):
            lines.append(f"Next step: `{payload.get('next_step')}`")
        if payload.get("receipt_path"):
            lines.append(f"Receipt: `{payload.get('receipt_path')}`")
        if payload.get("applied"):
            lines += ["", "## Files"]
            for item in payload.get("applied", []):
                lines.append(f"- `{item.get('path')}` backup=`{item.get('backup')}`")
        if payload.get("validation"):
            lines += ["", "## Validation"]
            for item in payload.get("validation", []):
                lines.append(f"- {'PASS' if item.get('ok') else 'FAIL'} `{item.get('command')}` ({item.get('seconds')}s)")
    return "\n".join(lines)
